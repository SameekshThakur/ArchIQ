import type { Workspace } from './useWorkspace';

const esc = (v: unknown) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const verdictText = { go: 'Ready', conditional: 'Conditional', no_go: 'Not ready' } as const;
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'analysis';

export function reportFileName(w: Workspace, ext: 'md' | 'html', now = new Date()) {
  return `archiq-${slug(w.domain?.name ?? 'analysis')}-analysis-${now.toISOString().slice(0, 10)}.${ext}`;
}

/** The analysis as Markdown, for pasting into a ticket, a wiki page or an ARB submission. */
export function reportMarkdown(w: Workspace, now = new Date()): string {
  const r = w.result;
  const L: string[] = [];
  L.push(`# ArchIQ analysis: ${w.domain?.name ?? ''}`, '');
  L.push(`- **Goal:** ${w.intent?.label ?? ''}${w.intent?.text ? ` (“${w.intent.text}”)` : ''}`, `- **Domain:** ${w.domain?.name ?? ''}`, `- **Generated:** ${now.toISOString().slice(0, 10)}`, '');
  if (r) {
    L.push('## Summary', '');
    if (r.verdict) L.push(`**Overall readiness: ${verdictText[r.verdict]}**`, '');
    L.push(r.headline, '');
    for (const n of r.notes) L.push(`> ${n}`, '');
  }
  if (w.documents.length) {
    L.push('## Files analysed', '', '| File | Treated as |', '|---|---|');
    for (const d of w.documents) L.push(`| ${d.name} | ${d.role ?? 'document'} |`);
    L.push('');
  }
  L.push('## What was done', '');
  for (const s of w.steps) L.push(`- **${s.label}**: ${s.status}${s.detail ? `, ${s.detail}` : ''}`);
  L.push('');
  for (const s of r?.sections ?? []) {
    L.push(`## ${s.title}`, '', s.metrics.map((m) => `**${m.label}:** ${m.value}`).join(' · '), '');
    for (const b of s.bullets) L.push(`- ${b}`);
    if (s.bullets.length) L.push('');
  }
  L.push('---', '', '_Generated by ArchIQ using its offline rules and pattern engines. Review before relying on it._', '');
  return L.join('\n');
}

/** A single self-contained page that prints cleanly to PDF from any browser. */
export function reportHtml(w: Workspace, now = new Date()): string {
  const r = w.result;
  const tone = r?.verdict === 'go' ? '#15803d' : r?.verdict === 'conditional' ? '#b45309' : '#b91c1c';
  const sections = (r?.sections ?? []).map((s) => `
    <section><h2>${esc(s.title)}</h2>
      <dl>${s.metrics.map((m) => `<div><dt>${esc(m.label)}</dt><dd>${esc(m.value)}</dd></div>`).join('')}</dl>
      ${s.bullets.length ? `<ul>${s.bullets.map((b) => `<li>${esc(b)}</li>`).join('')}</ul>` : ''}</section>`).join('');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>ArchIQ analysis: ${esc(w.domain?.name)}</title>
<style>
 body{font:15px/1.55 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#111827;max-width:860px;margin:32px auto;padding:0 20px}
 h1{font-size:24px;margin:0 0 4px} h2{font-size:17px;margin:28px 0 8px;border-bottom:1px solid #e5e7eb;padding-bottom:4px}
 .meta{color:#4b5563;font-size:13px} .verdict{display:inline-block;padding:2px 10px;border-radius:999px;color:#fff;font-weight:600;font-size:13px;background:${tone}}
 .note{color:#4b5563;font-size:13px;border-left:3px solid #d1d5db;padding-left:10px;margin:8px 0}
 table{border-collapse:collapse;width:100%;font-size:14px} td,th{border-bottom:1px solid #e5e7eb;padding:5px 8px;text-align:left}
 dl{display:flex;flex-wrap:wrap;gap:8px 28px;margin:0 0 6px} dt{font-size:12px;color:#6b7280} dd{margin:0;font-size:20px;font-weight:600}
 ul{margin:6px 0 0;padding-left:20px;font-size:14px;color:#374151} footer{margin-top:36px;color:#6b7280;font-size:12px}
 section{break-inside:avoid} @media print{body{margin:12mm}}
</style></head><body>
<h1>ArchIQ analysis: ${esc(w.domain?.name)}</h1>
<p class="meta">Goal: ${esc(w.intent?.label)}${w.intent?.text ? ` (“${esc(w.intent.text)}”)` : ''} · Generated ${esc(now.toISOString().slice(0, 10))}</p>
${r ? `<p>${r.verdict ? `<span class="verdict">${verdictText[r.verdict]}</span> ` : ''}${esc(r.headline)}</p>${r.notes.map((n) => `<p class="note">${esc(n)}</p>`).join('')}` : ''}
${w.documents.length ? `<h2>Files analysed</h2><table><tr><th>File</th><th>Treated as</th></tr>${w.documents.map((d) => `<tr><td>${esc(d.name)}</td><td>${esc(d.role ?? 'document')}</td></tr>`).join('')}</table>` : ''}
<h2>What was done</h2><ul>${w.steps.map((s) => `<li><b>${esc(s.label)}</b>: ${esc(s.status)}${s.detail ? `, ${esc(s.detail)}` : ''}</li>`).join('')}</ul>
${sections}
<footer>Generated by ArchIQ using its offline rules and pattern engines. Review before relying on it.</footer>
</body></html>`;
}
